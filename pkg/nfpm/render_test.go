// TestRenderPKGBUILD_ChangelogWritesSidecar covers acceptance case: a
// changelog with a non-empty OutputDir writes "<name>.changelog" in the
// RPM %changelog dialect and the PKGBUILD carries the matching directive.
func TestRenderPKGBUILD_ChangelogWritesSidecar(t *testing.T) {
	cfg := &nfpm.Config{
		Info: nfpm.Info{Name: "examplepkg", Version: "1.0.0", Changelog: "changelog.yaml"},
	}
	cfg.SetBaseDir("testdata")

	outDir := t.TempDir()

	data, messages, err := cfg.RenderPKGBUILD(&nfpm.RenderOptions{OutputDir: outDir})
	require.NoError(t, err)
	assert.Empty(t, messages)
	assert.Contains(t, string(data), `changelog="examplepkg.changelog"`)

	sidecar, err := os.ReadFile(filepath.Join(outDir, "examplepkg.changelog"))
	require.NoError(t, err)

	headers := rpmChangelogHeaderLines(t, sidecar)
	assert.NotEmpty(t, headers)
	assert.Contains(t, string(sidecar), "- Fix crash on startup\n")
}

// TestRenderPKGBUILD_ChangelogNoOutputDir covers acceptance case: a
