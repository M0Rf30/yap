// TestRenderPKGBUILD_ChangelogUnreadableIsHardError covers acceptance case:
// a changelog: path that cannot be loaded is a hard, typed error.
func TestRenderPKGBUILD_ChangelogUnreadableIsHardError(t *testing.T) {
	cfg := &nfpm.Config{
		Info: nfpm.Info{Name: "myapp", Version: "1.0.0", Changelog: "does-not-exist.yaml"},
	}
	cfg.SetBaseDir("testdata")

	_, _, err := cfg.RenderPKGBUILD(nil)
	require.Error(t, err)

	var yerr *yaperrors.YapError
	require.True(t, errors.As(err, &yerr))
	assert.Equal(t, yaperrors.ErrTypeFileSystem, yerr.Type)
}
